import 'dart:typed_data';

/// Virtual 192 × 63 4-level grayscale framebuffer and bitmap glyph engine
/// for the Cal_ 1100_DB_ dot-matrix LCD.
class LcdFrameBuffer {
  final int width;
  final int height;
  final Uint8List pixels;

  LcdFrameBuffer({this.width = 192, this.height = 63})
      : pixels = Uint8List(width * height);

  /// Clears all pixels to Shade 0 (background).
  void clear([int shade = 0]) {
    pixels.fillRange(0, pixels.length, shade);
  }

  /// Sets a single pixel at (x, y) to shade (0..4).
  void setPixel(int x, int y, int shade) {
    if (x < 0 || x >= width || y < 0 || y >= height) return;
    pixels[y * width + x] = shade;
  }

  /// Gets the shade (0..4) at (x, y).
  int getPixel(int x, int y) {
    if (x < 0 || x >= width || y < 0 || y >= height) return 0;
    return pixels[y * width + x];
  }

  /// Computes a fast 32-bit FNV-1a content signature over all $192 \times 63$ pixels
  /// so `CustomPainter.shouldRepaint` only redraws when the LCD buffer changes.
  int computeSignature() {
    int hash = 0x811c9dc5;
    for (int i = 0; i < pixels.length; i++) {
      hash ^= pixels[i];
      hash = (hash * 0x01000193) & 0x7fffffff;
    }
    return hash;
  }

  /// Fills a solid rectangle with [shade].
  void fillRect(int x, int y, int w, int h, int shade) {
    for (int py = y; py < y + h; py++) {
      for (int px = x; px < x + w; px++) {
        setPixel(px, py, shade);
      }
    }
  }

  /// Draws a 1px rectangular outline.
  void drawRectOutline(int x, int y, int w, int h, int shade) {
    for (int px = x; px < x + w; px++) {
      setPixel(px, y, shade);
      setPixel(px, y + h - 1, shade);
    }
    for (int py = y; py < y + h; py++) {
      setPixel(x, py, shade);
      setPixel(x + w - 1, py, shade);
    }
  }

  /// Draws a horizontal line with optional dotted stride.
  void drawHLine(int x, int y, int length, int shade, {int step = 1}) {
    for (int px = x; px < x + length; px += step) {
      setPixel(px, y, shade);
    }
  }

  /// Draws a vertical line.
  void drawVLine(int x, int y, int length, int shade, {int step = 1}) {
    for (int py = y; py < y + length; py += step) {
      setPixel(x, py, shade);
    }
  }

  /// Draws a 5×7 dot-matrix character glyph at (x, y).
  /// Returns the horizontal advance width (6px standard).
  int drawGlyph5x7(
    String char,
    int x,
    int y, {
    int shade = 4,
    bool bold = false,
  }) {
    final List<int> rows = LcdBitmapFont.glyphFor(char);
    for (int r = 0; r < rows.length; r++) {
      final int rowBits = rows[r];
      for (int c = 0; c < 5; c++) {
        if ((rowBits & (1 << (4 - c))) != 0) {
          setPixel(x + c, y + r, shade);
          if (bold) {
            setPixel(x + c + 1, y + r, shade);
          }
        }
      }
    }
    return bold ? 7 : 6;
  }

  /// Draws a string using the 5×7 dot-matrix font.
  int drawText(
    String text,
    int x,
    int y, {
    int shade = 4,
    bool bold = false,
    int letterSpacing = 1,
  }) {
    int cursorX = x;
    for (int i = 0; i < text.length; i++) {
      final ch = text[i];
      final List<int> rows = LcdBitmapFont.glyphFor(ch);
      for (int r = 0; r < rows.length; r++) {
        final int rowBits = rows[r];
        for (int c = 0; c < 5; c++) {
          if ((rowBits & (1 << (4 - c))) != 0) {
            setPixel(cursorX + c, y + r, shade);
            if (bold) {
              setPixel(cursorX + c + 1, y + r, shade);
            }
          }
        }
      }
      cursorX += 5 + (bold ? 1 : 0) + letterSpacing;
    }
    return cursorX - x;
  }

  /// Measures the pixel width of [text] in the 5×7 font.
  int measureText(String text, {bool bold = false, int letterSpacing = 1}) {
    if (text.isEmpty) return 0;
    final int charWidth = 5 + (bold ? 1 : 0) + letterSpacing;
    return text.length * charWidth - letterSpacing;
  }

  /// Draws a compact 3×5 micro-text badge in the 8px status bar.
  int drawStatusBadge(
    String label,
    int x,
    int y, {
    required bool active,
    bool inverted = true,
  }) {
    final int charCount = label.length;
    final int badgeW = charCount * 4 + 3;
    const int badgeH = 7;

    if (active) {
      if (inverted) {
        fillRect(x, y, badgeW, badgeH, 4);
        // Cut 1px corners for authentic Cal_ rounded status badge look
        setPixel(x, y, 0);
        setPixel(x + badgeW - 1, y, 0);
        setPixel(x, y + badgeH - 1, 0);
        setPixel(x + badgeW - 1, y + badgeH - 1, 0);
        _drawMicroText3x5(label, x + 2, y + 1, shade: 0);
      } else {
        _drawMicroText3x5(label, x + 1, y + 1, shade: 4);
      }
    } else {
      // Ghosted inactive LCD segment preview in Shade 1
      _drawMicroText3x5(label, x + 1, y + 1, shade: 1);
    }
    return badgeW;
  }

  void _drawMicroText3x5(String text, int x, int y, {required int shade}) {
    int cx = x;
    for (int i = 0; i < text.length; i++) {
      final rows = LcdBitmapFont.microGlyph3x5(text[i]);
      for (int r = 0; r < 5; r++) {
        final bits = rows[r];
        for (int c = 0; c < 3; c++) {
          if ((bits & (1 << (2 - c))) != 0) {
            setPixel(cx + c, y + r, shade);
          }
        }
      }
      cx += 4;
    }
  }
}

